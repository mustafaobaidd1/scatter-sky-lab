// Builds the small spectral tables in src/physics/data/ from the original published files.
//
// The raw files are not committed (size and licences). Download them into one folder, then run
//   node scripts/build-spectral-tables.mjs <folder>
//
//   ASTMG173.csv                         ASTM G173-03 reference spectra (NREL / NLR, astmg173.zip)
//   serdyuchenkogorshelev5digits.dat     O3 cross-sections, IUP Bremen (Serdyuchenko et al. 2014)
//   CIE_xyz_1931_2deg.csv                CIE 1931 2° colour-matching functions, 1 nm (CC BY-SA 4.0)
//   CIE_std_illum_D65.csv                CIE standard illuminant D65, 1 nm (CC BY-SA 4.0)
//
// Every output table lives on the same 5 nm grid, 360–830 nm (95 values).
// Solar irradiance and ozone cross-sections are box averages over [λ − 2.5, λ + 2.5] nm
// (trapezoidal integration of the high-resolution data), so narrow Fraunhofer lines and
// absorption features are averaged rather than point-sampled. The CIE tables are the official
// values at each 5 nm wavelength (the CIE's own abridged tables are the same subsample).
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) {
  console.error('usage: node scripts/build-spectral-tables.mjs <folder-with-raw-files>');
  process.exit(1);
}

const START = 360;
const STEP = 5;
const COUNT = 95; // 360..830
const grid = Array.from({ length: COUNT }, (_, i) => START + i * STEP);

/** Parses whitespace- or comma-separated numeric rows, skipping anything non-numeric. */
function parseRows(text) {
  const rows = [];
  for (const line of text.split(/\r?\n/)) {
    const parts = line.trim().split(/[\s,]+/);
    if (parts.length < 2) continue;
    const nums = parts.map(Number);
    if (nums.some((n) => !Number.isFinite(n))) continue;
    rows.push(nums);
  }
  return rows;
}

/** Box average of a piecewise-linear tabulated function over [a, b] (trapezoidal rule). */
function boxAverage(xs, ys, a, b) {
  let area = 0;
  for (let i = 0; i < xs.length - 1; i++) {
    const x0 = xs[i];
    const x1 = xs[i + 1];
    if (x1 <= a || x0 >= b) continue;
    const lo = Math.max(a, x0);
    const hi = Math.min(b, x1);
    const t0 = (lo - x0) / (x1 - x0);
    const t1 = (hi - x0) / (x1 - x0);
    const y0 = ys[i] + (ys[i + 1] - ys[i]) * t0;
    const y1 = ys[i] + (ys[i + 1] - ys[i]) * t1;
    area += 0.5 * (y0 + y1) * (hi - lo);
  }
  return area / (b - a);
}

function sig(x, digits = 5) {
  return Number(x.toPrecision(digits));
}

function formatArray(values, perLine = 8) {
  const lines = [];
  for (let i = 0; i < values.length; i += perLine) {
    lines.push('  ' + values.slice(i, i + perLine).join(', ') + ',');
  }
  return lines.join('\n');
}

// --- ASTM G173 extraterrestrial (ETR) column -------------------------------------------------
const g173 = parseRows(readFileSync(join(dir, 'ASTMG173.csv'), 'utf8'));
const g173x = g173.map((r) => r[0]);
const g173y = g173.map((r) => r[1]);
const solar = grid.map((l) => sig(boxAverage(g173x, g173y, l - 2.5, l + 2.5)));

// Cross-check against the 10 nm bin averages tabulated in Bruneton's demo (BSD) for 360-370 nm,
// 550-560 nm and 700-710 nm: 1.11776, 1.8504, 1.41018 W m^-2 nm^-1.
for (const [a, ref] of [
  [360, 1.11776],
  [550, 1.8504],
  [700, 1.41018],
]) {
  const v = boxAverage(g173x, g173y, a, a + 10);
  console.log(`G173 ETR mean ${a}-${a + 10} nm: ${v.toFixed(5)} (Bruneton ${ref})`);
}

// --- Ozone absorption cross-section (IUP Bremen, 223 K column) -------------------------------
// Columns: 1 wavelength (vacuum, nm), then 293 K, 283 K, ..., 193 K. Column index 8 is 223 K,
// the temperature closest to the ozone-layer peak (US Standard Atmosphere: 221.6 K at 25 km).
const o3 = parseRows(readFileSync(join(dir, 'serdyuchenkogorshelev5digits.dat'), 'utf8')).filter(
  (r) => r.length >= 12,
);
const O3_COLUMN = 8;
const o3x = o3.map((r) => r[0]);
const o3y = o3.map((r) => r[O3_COLUMN] * 1e-4); // cm^2 -> m^2
const ozone = grid.map((l) => sig(Math.max(0, boxAverage(o3x, o3y, l - 2.5, l + 2.5)), 4));
const o3at = (a) => boxAverage(o3x, o3y, a, a + 10);
console.log(
  `O3 223 K mean 600-610 nm: ${o3at(600).toExponential(4)} m^2 (Bruneton 233 K: 5.019e-25)`,
);

// --- CIE 1931 2° CMFs and D65 ------------------------------------------------------------------
const cmf = parseRows(readFileSync(join(dir, 'CIE_xyz_1931_2deg.csv'), 'utf8'));
const cmfAt = new Map(cmf.map((r) => [Math.round(r[0]), r]));
const xbar = grid.map((l) => cmfAt.get(l)[1]);
const ybar = grid.map((l) => cmfAt.get(l)[2]);
const zbar = grid.map((l) => cmfAt.get(l)[3]);
const d65rows = parseRows(readFileSync(join(dir, 'CIE_std_illum_D65.csv'), 'utf8'));
const d65At = new Map(d65rows.map((r) => [Math.round(r[0]), r[1]]));
const d65 = grid.map((l) => d65At.get(l));

const header = `// Generated by scripts/build-spectral-tables.mjs — do not edit by hand.
// Grid: 360–830 nm in 5 nm steps (95 values).`;

writeFileSync(
  'src/physics/data/solar.ts',
  `${header}
//
// Extraterrestrial solar spectral irradiance at 1 AU, W m^-2 nm^-1: the ETR column of the
// ASTM G173-03 reference spectra (derived from SMARTS v2.9.2, Gueymard), distributed by the
// U.S. DOE National Laboratory of the Rockies (formerly NREL),
// https://www.nlr.gov/grid/solar-resource/spectra-am1.5 — free to use with credit to DOE/NLR.
// Each value is the box average over [λ − 2.5, λ + 2.5] nm.
export const SOLAR_IRRADIANCE_5NM: readonly number[] = [
${formatArray(solar)}
];
`,
);

writeFileSync(
  'src/physics/data/ozone.ts',
  `${header}
//
// Ozone absorption cross-section at 223 K, m^2 per molecule, from the IUP Bremen broadband
// measurements: A. Serdyuchenko, V. Gorshelev, M. Weber, W. Chehade, J. P. Burrows (2014),
// "High spectral resolution ozone absorption cross-sections – Part 2: Temperature dependence",
// Atmos. Meas. Tech. 7, 625–636, doi:10.5194/amt-7-625-2014 (data: iup.uni-bremen.de, molspec).
// Each value is the box average over [λ − 2.5, λ + 2.5] nm of the 0.01 nm data.
export const OZONE_CROSS_SECTION_5NM: readonly number[] = [
${formatArray(ozone)}
];
`,
);

writeFileSync(
  'src/physics/data/cie.ts',
  `${header}
//
// LICENCE: this file (and only this file) is licensed CC BY-SA 4.0
// (https://creativecommons.org/licenses/by-sa/4.0/), because it is derived from CIE datasets:
//   CIE (2019) Colour-matching functions of CIE 1931 standard colorimetric observer,
//   doi:10.25039/CIE.DS.xvudnb9b (CIE_xyz_1931_2deg.csv)
//   CIE (2019) CIE standard illuminant D65, doi:10.25039/CIE.DS.hjfjmt59 (CIE_std_illum_D65.csv)
// The values below are the official 1 nm values subsampled at 5 nm, unchanged.

/** CIE 1931 2° colour-matching function x̄(λ). */
export const CIE_X_5NM: readonly number[] = [
${formatArray(xbar)}
];

/** CIE 1931 2° colour-matching function ȳ(λ) (equals V(λ)). */
export const CIE_Y_5NM: readonly number[] = [
${formatArray(ybar)}
];

/** CIE 1931 2° colour-matching function z̄(λ). */
export const CIE_Z_5NM: readonly number[] = [
${formatArray(zbar)}
];

/** CIE standard illuminant D65, relative spectral power (100 at 560 nm). */
export const CIE_D65_5NM: readonly number[] = [
${formatArray(d65)}
];
`,
);

console.log('wrote src/physics/data/{solar,ozone,cie}.ts');
